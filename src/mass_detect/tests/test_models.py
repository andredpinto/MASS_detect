"""Unit tests (run with: pytest tests)."""
import numpy as np
import pandas as pd
from src.mass_detect.scripts.models import OrdinalLogisticRegression, ReferenceBatchComBat
from src.mass_detect.scripts.validation import all_metrics, check_submission

def synthetic_ordinal(n=600, seed=0): # Ratings 1..5 generated by a proportional odds model with known weights.
    rng = np.random.default_rng(seed)
    X = rng.normal(size=(n, 3))
    latent = X @ np.array([1.5, -1.0, 0.0]) + rng.logistic(size=n)
    return X, 1 + np.searchsorted([-2.0, -0.5, 0.5, 2.0], latent)

def test_probabilities_are_valid():
    X, y = synthetic_ordinal()
    proba = OrdinalLogisticRegression(alpha=1.0).fit(X, y).predict_proba(X)
    assert proba.shape == (len(y), 5)
    assert np.all(proba >= 0) and np.allclose(proba.sum(axis=1), 1)

def test_recovers_the_true_weights_and_cut_points():
    X, y = synthetic_ordinal(n=5000)
    model = OrdinalLogisticRegression(alpha=0.0).fit(X, y)
    assert model.converged_
    assert np.allclose(model.coef_, [1.5, -1.0, 0.0], atol=0.15)
    assert np.allclose(model.cuts_, [-2.0, -0.5, 0.5, 2.0], atol=0.2)

def test_cut_points_stay_in_order():
    X, y = synthetic_ordinal()
    assert np.all(np.diff(OrdinalLogisticRegression().fit(X, y).cuts_) > 0)

def test_median_and_argmax_are_classes():
    X, y = synthetic_ordinal()
    model = OrdinalLogisticRegression().fit(X, y)
    assert set(model.predict(X)) <= set(range(1, 6)) and set(model.predict_median(X)) <= set(range(1, 6))

def test_combat_leaves_the_reference_untouched_and_removes_a_shift():
    rng = np.random.default_rng(1)
    batch = np.array(["LNDb"] * 300 + ["LIDC_GE"] * 300)
    label = rng.integers(1, 6, size=600).astype(float)
    # The ComBat model: same label effect in both batches; the scanner adds a shift and scales the noise
    noise = rng.normal(size=600) * np.where(batch == "LNDb", 1.0, 3.0)
    value = 10 * label + noise + np.where(batch == "LNDb", 0.0, 50.0)
    X = pd.DataFrame({"f": value})
    combat = ReferenceBatchComBat(["f"]).fit(X, batch, label)
    out = combat.transform(X, batch, label)["f"].to_numpy()
    lndb, lidc = batch == "LNDb", batch == "LIDC_GE"
    assert np.allclose(out[lndb], value[lndb])                                  # reference untouched
    residual = lambda rows: out[rows] - 10 * label[rows]
    assert abs(residual(lidc).mean() - residual(lndb).mean()) < 0.5            # shift of 50 removed
    assert abs(residual(lidc).std() / residual(lndb).std() - 1) < 0.15         # noise scale of 3 removed

def test_metrics_of_a_perfect_prediction():
    y = np.array([1, 2, 3, 4, 5, 3, 2])
    scores = all_metrics(y, y)
    assert scores["qwk"] == 1 and scores["mae"] == 0 and scores["composite"] == 3

def test_check_submission_catches_wrong_files():
    test = pd.DataFrame({"LNDbID": [1, 1, 2], "FindingID": [1, 2, 1]})
    good = test.assign(prediction=[1, 3, 5])
    assert check_submission(good, test)
    for bad in (good.iloc[::-1].reset_index(drop=True), good.assign(prediction=[0, 3, 5]),
                good.assign(prediction=[1.0, 3.0, np.nan]), good.iloc[:2]):
        try: check_submission(bad, test)
        except AssertionError: continue
        raise AssertionError("a wrong submission was accepted")
